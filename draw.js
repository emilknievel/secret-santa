// Draws names and writes public/data.js plus links.txt.
// Usage: node draw.js <site-url>    e.g. node draw.js https://santa.example.com/
//    or: SITE_URL=https://santa.example.com/ node draw.js
// Running it again makes a brand new draw (and new links).

import { writeFileSync } from "node:fs";
import { randomBytes, randomInt } from "node:crypto";
import { idFor, seal } from "./public/cipher.js";

const NAMES = ["Emil", "Niklas", "Lollo", "Ulli", "Martin", "Jennie", "Phoebe"];

const site = process.argv[2] ?? process.env.SITE_URL;
if (!site) console.warn("No site URL given, so the links point at localhost. See the usage note in draw.js.\n");
const base = (site ?? "http://localhost:8000/").replace(/\/?$/, "/");

// Shuffle until nobody draws themselves.
function derangement(list) {
  for (;;) {
    const out = [...list];
    for (let i = out.length - 1; i > 0; i--) {
      const j = randomInt(i + 1);
      [out[i], out[j]] = [out[j], out[i]];
    }
    if (out.every((name, i) => name !== list[i])) return out;
  }
}

const receivers = derangement(NAMES);
const entries = NAMES.map((giver, i) => {
  const token = randomBytes(6).toString("base64url");
  return { giver, token, id: idFor(token), gift: seal(token, receivers[i]) };
});

const data = entries.map(({ id, giver, gift }) => ({ id, giver, gift }));
writeFileSync(
  new URL("./public/data.js", import.meta.url),
  `// Generated by draw.js. Do not edit by hand.\nexport default ${JSON.stringify(data, null, 2)};\n`,
);

const links = entries.map(({ giver, token }) => `${giver.padEnd(8)} ${base}#${token}`).join("\n");
writeFileSync(new URL("./links.txt", import.meta.url), links + "\n");

console.log("Names drawn! Send each person their own link:\n");
console.log(links);
console.log("\n(Saved to links.txt, which is git-ignored.)");
